-- 동글맵 장소 신고. 자동 숨김 없이 관리자가 확인해 숨김·수정(RESOLVED)하거나 기각(REJECTED)한다.
-- 신고자는 member FK 없이 ID로만 참조하며 탈퇴 시 reporter_id를 비운다.
CREATE TABLE public.place_report (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    place_id bigint NOT NULL,
    reporter_id bigint,
    reason character varying(20) NOT NULL,
    description character varying(200),
    status character varying(10) NOT NULL,
    processed_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT place_report_pkey PRIMARY KEY (id),
    CONSTRAINT place_report_place_id_fkey FOREIGN KEY (place_id) REFERENCES public.place (id) ON DELETE CASCADE,
    CONSTRAINT place_report_reason_check CHECK (
        reason IN ('CLOSED', 'WRONG_LOCATION', 'WRONG_NAME', 'DUPLICATE', 'INAPPROPRIATE', 'OTHER')),
    CONSTRAINT place_report_status_check CHECK (status IN ('PENDING', 'RESOLVED', 'REJECTED')),
    CONSTRAINT place_report_other_description_check CHECK (reason <> 'OTHER' OR description IS NOT NULL),
    CONSTRAINT place_report_processed_at_check CHECK ((status = 'PENDING') = (processed_at IS NULL))
);

-- 회원당 장소별 처리 대기 신고 1건. 처리된 신고는 제외해 재신고를 허용한다.
CREATE UNIQUE INDEX uk_place_report_pending ON public.place_report USING btree (place_id, reporter_id)
    WHERE status = 'PENDING';
CREATE INDEX idx_place_report_place_id ON public.place_report USING btree (place_id, status);
CREATE INDEX idx_place_report_status ON public.place_report USING btree (status, created_at);
CREATE INDEX idx_place_report_reporter_id ON public.place_report USING btree (reporter_id);
