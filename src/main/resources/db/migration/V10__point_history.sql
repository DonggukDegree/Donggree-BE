-- 회원 포인트 적립 내역. 회원은 member FK 없이 ID로만 참조하며 탈퇴 시 그 회원의 행을 지운다.
-- 대상이 숨겨지면 revoked_at을 기록해 합계에서 빼고, 숨김이 풀리면 비운다.
CREATE TABLE public.point_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    member_id bigint NOT NULL,
    reason character varying(40) NOT NULL,
    amount integer NOT NULL,
    target_id bigint,
    revoked_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT point_history_pkey PRIMARY KEY (id),
    CONSTRAINT point_history_reason_check CHECK (reason IN (
        'GRADUATION_REPORT_FIRST_VIEW', 'PLACE_REGISTER', 'PLACE_FIRST_REVIEW', 'PLACE_REVIEW', 'PLACE_INFO_EDIT')),
    CONSTRAINT point_history_amount_check CHECK (amount > 0),
    CONSTRAINT point_history_target_check CHECK ((reason = 'GRADUATION_REPORT_FIRST_VIEW') = (target_id IS NULL))
);

-- 같은 회원·사유·대상은 한 번만 적립한다.
CREATE UNIQUE INDEX uk_point_history_target ON public.point_history USING btree (member_id, reason, target_id)
    WHERE target_id IS NOT NULL;
-- 졸업 리포트 최초 확인은 회원당 1회.
CREATE UNIQUE INDEX uk_point_history_report_first_view ON public.point_history USING btree (member_id)
    WHERE reason = 'GRADUATION_REPORT_FIRST_VIEW';
-- 리뷰 적립(첫 리뷰·일반 리뷰 합쳐)은 회원당 장소별 1회. 지웠다 다시 써도 다시 받지 않는다.
CREATE UNIQUE INDEX uk_point_history_review ON public.point_history USING btree (member_id, target_id)
    WHERE reason IN ('PLACE_FIRST_REVIEW', 'PLACE_REVIEW');
-- 장소 첫 리뷰 적립은 장소별 1명.
CREATE UNIQUE INDEX uk_point_history_first_review ON public.point_history USING btree (target_id)
    WHERE reason = 'PLACE_FIRST_REVIEW';
-- 내 적립 내역 최신순 조회.
CREATE INDEX idx_point_history_member_id ON public.point_history USING btree (member_id, id);
-- 숨김·해제 시 대상별 회수·복구.
CREATE INDEX idx_point_history_target_id ON public.point_history USING btree (target_id, reason);
