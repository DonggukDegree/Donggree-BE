-- 동아리 신규 등록·정보 수정·모집 등록 요청과 직접 수정 권한.
-- 요청자는 member FK 없이 ID로만 참조하며 탈퇴 시 비운다. 연락처·동아리와의 관계는 요청 1년 뒤 또는 탈퇴 시 비운다.
-- 변경 전(before_value)·요청(after_value) 값은 관리자 비교용 jsonb다. 신규 등록·새 모집은 변경 전 값이 없다.
CREATE TABLE public.club_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    type character varying(15) NOT NULL,
    club_id bigint,
    club_name character varying(30) NOT NULL,
    requester_id bigint,
    requester_role character varying(15),
    requester_contact character varying(100),
    status character varying(10) NOT NULL,
    before_value jsonb,
    after_value jsonb NOT NULL,
    reject_reason character varying(200),
    processed_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT club_request_pkey PRIMARY KEY (id),
    CONSTRAINT club_request_club_id_fkey FOREIGN KEY (club_id) REFERENCES public.club (id) ON DELETE CASCADE,
    CONSTRAINT club_request_type_check CHECK (type IN ('REGISTER', 'EDIT', 'RECRUITMENT')),
    CONSTRAINT club_request_status_check CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELED')),
    CONSTRAINT club_request_role_check CHECK (
        requester_role IS NULL OR requester_role IN ('PRESIDENT', 'STAFF', 'MEMBER', 'OUTSIDER')),
    CONSTRAINT club_request_club_check CHECK (type = 'REGISTER' OR club_id IS NOT NULL),
    CONSTRAINT club_request_processed_check CHECK ((status = 'PENDING') = (processed_at IS NULL)),
    CONSTRAINT club_request_reject_reason_check CHECK ((status = 'REJECTED') = (reject_reason IS NOT NULL))
);

-- 회원당 같은 동아리·종류의 검토 중 요청은 1건. 고치려면 다시 요청(기존 요청 취소)한다.
CREATE UNIQUE INDEX uk_club_request_pending ON public.club_request USING btree (requester_id, club_id, type)
    WHERE status = 'PENDING' AND club_id IS NOT NULL;
-- 내 요청 내역(최신순)·관리자 상태별 목록·보유 기간 경과 정리.
CREATE INDEX idx_club_request_requester_id ON public.club_request USING btree (requester_id, id);
CREATE INDEX idx_club_request_status ON public.club_request USING btree (status, id);
CREATE INDEX idx_club_request_created_at ON public.club_request USING btree (created_at)
    WHERE requester_contact IS NOT NULL OR requester_role IS NOT NULL;

-- 승인 없이 바로 수정할 수 있는 회원. 이 동아리의 요청이 승인되면 생기고 관리자가 회수할 수 있다.
CREATE TABLE public.club_editor (
    club_id bigint NOT NULL,
    member_id bigint NOT NULL,
    granted_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT club_editor_pkey PRIMARY KEY (club_id, member_id),
    CONSTRAINT club_editor_club_id_fkey FOREIGN KEY (club_id) REFERENCES public.club (id) ON DELETE CASCADE
);

CREATE INDEX idx_club_editor_member_id ON public.club_editor USING btree (member_id);
