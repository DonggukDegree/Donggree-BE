-- 동아리 쇼핑 목록 상단 광고 배너. 글자 배너는 배경(CSS 색·그라데이션)과 글자를, 이미지 배너는 PC(필수)·모바일 이미지와
-- 대체 텍스트(title)를 쓴다. 켜져 있고 노출 기간 안인 배너만 sort_order 순으로 공개한다.
CREATE TABLE public.club_banner (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    title character varying(30) NOT NULL,
    eyebrow character varying(12),
    description character varying(60),
    background character varying(200),
    image_url character varying(500),
    mobile_image_url character varying(500),
    link character varying(500) NOT NULL,
    starts_at timestamp(6) without time zone,
    ends_at timestamp(6) without time zone,
    active boolean NOT NULL,
    sort_order integer NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT club_banner_pkey PRIMARY KEY (id),
    CONSTRAINT club_banner_kind_check CHECK (
        (image_url IS NULL AND mobile_image_url IS NULL AND background IS NOT NULL)
        OR (image_url IS NOT NULL AND eyebrow IS NULL AND description IS NULL AND background IS NULL)),
    CONSTRAINT club_banner_period_check CHECK (starts_at IS NULL OR ends_at IS NULL OR starts_at < ends_at)
);

CREATE INDEX idx_club_banner_sort_order ON public.club_banner USING btree (sort_order, id);
