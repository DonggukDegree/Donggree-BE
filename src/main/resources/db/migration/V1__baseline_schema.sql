CREATE FUNCTION public.normalize_graduation_rule_roles(config jsonb) RETURNS jsonb
    LANGUAGE sql IMMUTABLE STRICT
    SET search_path TO 'pg_catalog'
    AS $$
SELECT CASE WHEN jsonb_typeof(config -> 'applicableMajorRoles') = 'array' THEN
                CASE WHEN NOT EXISTS (
                    SELECT 1 FROM jsonb_array_elements(config -> 'applicableMajorRoles') AS role(value)
                    WHERE jsonb_typeof(value) <> 'string'
                ) THEN jsonb_set(config, '{applicableMajorRoles}', COALESCE((
                                                                                SELECT jsonb_agg(value ORDER BY value)
                                                                                FROM (SELECT DISTINCT value
                                                                                      FROM jsonb_array_elements(config -> 'applicableMajorRoles') AS role(value)) AS roles
                                                                            ), '[]'::jsonb)) ELSE config END
            ELSE config END
$$;

