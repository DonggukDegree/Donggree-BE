-- 동아리·배너 사진. 파일은 홈서버 디스크(볼륨)에 stored_name으로 저장하고, 행은 메타데이터만 가진다.
-- 동아리 사진은 승인·바로 반영 때 동아리에 연결(club_id·sort_order)되며, 연결되지 않은 채 30일이 지나고 검토 중 요청에도
-- 쓰이지 않으면 매일 정리한다. 배너 사진(BANNER)은 정리하지 않는다. 업로더는 member FK 없이 ID로만 참조한다.
CREATE TABLE public.club_image (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    stored_name character varying(60) NOT NULL,
    content_type character varying(20) NOT NULL,
    size_bytes integer NOT NULL,
    purpose character varying(10) NOT NULL,
    uploader_id bigint,
    club_id bigint,
    sort_order integer,
    representative boolean NOT NULL DEFAULT false,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT club_image_pkey PRIMARY KEY (id),
    CONSTRAINT club_image_stored_name_key UNIQUE (stored_name),
    CONSTRAINT club_image_club_id_fkey FOREIGN KEY (club_id) REFERENCES public.club (id),
    CONSTRAINT club_image_purpose_check CHECK (purpose IN ('CLUB', 'BANNER')),
    CONSTRAINT club_image_content_type_check CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT club_image_size_check CHECK (size_bytes BETWEEN 1 AND 5242880),
    CONSTRAINT club_image_attach_check CHECK ((club_id IS NULL) = (sort_order IS NULL)),
    CONSTRAINT club_image_representative_check CHECK (NOT representative OR club_id IS NOT NULL)
);

-- 동아리 사진 조회(대표 먼저, 순서대로)·연결 안 된 사진 정리.
CREATE INDEX idx_club_image_club_id ON public.club_image USING btree (club_id, sort_order) WHERE club_id IS NOT NULL;
CREATE INDEX idx_club_image_unattached ON public.club_image USING btree (created_at)
    WHERE club_id IS NULL AND purpose = 'CLUB';
