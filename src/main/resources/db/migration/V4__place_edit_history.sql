-- 동글맵 장소 정보(영업시간·설명·메뉴) 수정 이력. 이력 화면 없이 관리자가 DB에서 확인·복구한다.
-- 메뉴는 변경 전후 목록 전체를 JSON 배열로 저장한다.
-- 수정자는 member FK 없이 ID로만 참조하며 탈퇴 시 editor_id를 비운다.
CREATE TABLE public.place_edit_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    place_id bigint NOT NULL,
    editor_id bigint,
    before_business_hours character varying(100),
    after_business_hours character varying(100),
    before_description character varying(300),
    after_description character varying(300),
    before_menus jsonb NOT NULL,
    after_menus jsonb NOT NULL,
    edited_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT place_edit_history_pkey PRIMARY KEY (id),
    CONSTRAINT place_edit_history_place_id_fkey FOREIGN KEY (place_id) REFERENCES public.place (id) ON DELETE CASCADE,
    CONSTRAINT place_edit_history_menus_check CHECK (
        jsonb_typeof(before_menus) = 'array' AND jsonb_typeof(after_menus) = 'array')
);

CREATE INDEX idx_place_edit_history_place_id ON public.place_edit_history USING btree (place_id, edited_at);
CREATE INDEX idx_place_edit_history_editor_id ON public.place_edit_history USING btree (editor_id);
