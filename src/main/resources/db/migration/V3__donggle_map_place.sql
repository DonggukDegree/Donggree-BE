-- 동글맵 장소·메뉴. 좌표는 사용자가 지도에서 지정한 값만 저장하고 주소는 저장하지 않는다.
-- 회원은 member FK 없이 ID로만 참조하며 탈퇴 시 created_by를 비운다.
CREATE TABLE public.place (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name character varying(30) NOT NULL,
    category character varying(20) NOT NULL,
    sub_category character varying(30) NOT NULL,
    latitude double precision NOT NULL,
    longitude double precision NOT NULL,
    business_hours character varying(100),
    description character varying(300),
    status character varying(10) NOT NULL,
    version bigint NOT NULL,
    created_by bigint,
    info_updated_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT place_pkey PRIMARY KEY (id),
    CONSTRAINT place_latitude_check CHECK (latitude >= -90 AND latitude <= 90),
    CONSTRAINT place_longitude_check CHECK (longitude >= -180 AND longitude <= 180),
    CONSTRAINT place_status_check CHECK (status IN ('VISIBLE', 'HIDDEN'))
);

CREATE INDEX idx_place_status_location ON public.place USING btree (status, latitude, longitude);
CREATE INDEX idx_place_created_by ON public.place USING btree (created_by);

CREATE TABLE public.place_menu (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    place_id bigint NOT NULL,
    name character varying(30) NOT NULL,
    price integer,
    sort_order integer NOT NULL,
    CONSTRAINT place_menu_pkey PRIMARY KEY (id),
    CONSTRAINT place_menu_place_id_fkey FOREIGN KEY (place_id) REFERENCES public.place (id) ON DELETE CASCADE,
    CONSTRAINT place_menu_price_check CHECK (price IS NULL OR (price >= 0 AND price <= 1000000))
);

CREATE INDEX idx_place_menu_place_id ON public.place_menu USING btree (place_id);
