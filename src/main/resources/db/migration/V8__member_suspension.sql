-- 회원 이용 제한(정지). 현재 정지 종료 시각은 member에 두어 요청마다 빠르게 확인하고, 이력은 member_suspension에 남긴다.
-- 정지는 탈퇴·재가입(같은 회원 ID 재활성화)으로 풀리지 않는다.
ALTER TABLE public.member ADD COLUMN suspended_until timestamp(6) without time zone;

CREATE TABLE public.member_suspension (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    member_id bigint NOT NULL,
    days integer NOT NULL,
    source character varying(10) NOT NULL,
    report_type character varying(10),
    report_id bigint,
    note character varying(200),
    starts_at timestamp(6) without time zone NOT NULL,
    ends_at timestamp(6) without time zone NOT NULL,
    created_by bigint NOT NULL,
    lifted_at timestamp(6) without time zone,
    lifted_by bigint,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT member_suspension_pkey PRIMARY KEY (id),
    CONSTRAINT member_suspension_member_id_fkey FOREIGN KEY (member_id) REFERENCES public.member (id),
    CONSTRAINT member_suspension_days_check CHECK (days >= 1 AND ends_at > starts_at),
    CONSTRAINT member_suspension_source_check CHECK (source IN ('REPORT', 'ADMIN')),
    CONSTRAINT member_suspension_report_check CHECK (
        (source = 'REPORT' AND report_type IN ('PLACE', 'REVIEW') AND report_id IS NOT NULL)
        OR (source = 'ADMIN' AND report_type IS NULL AND report_id IS NULL))
);

CREATE INDEX idx_member_suspension_member_id ON public.member_suspension USING btree (member_id, id);
