-- 동글맵 장소 리뷰와 리뷰 신고. 작성자·신고자는 member FK 없이 ID로만 참조하며 탈퇴 시 비운다.
-- 작성자 삭제는 행을 지우지 않고 deleted_at만 기록해 신고 이력을 보존한다.
CREATE TABLE public.place_review (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    place_id bigint NOT NULL,
    author_id bigint,
    rating integer NOT NULL,
    content character varying(500) NOT NULL,
    status character varying(10) NOT NULL,
    deleted_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT place_review_pkey PRIMARY KEY (id),
    CONSTRAINT place_review_place_id_fkey FOREIGN KEY (place_id) REFERENCES public.place (id) ON DELETE CASCADE,
    CONSTRAINT place_review_rating_check CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT place_review_content_check CHECK (char_length(content) BETWEEN 10 AND 500),
    CONSTRAINT place_review_status_check CHECK (status IN ('VISIBLE', 'HIDDEN'))
);

-- 회원당 장소별 리뷰 1건. 작성자가 지운 리뷰는 제외해 다시 쓸 수 있게 한다.
CREATE UNIQUE INDEX uk_place_review_author ON public.place_review USING btree (place_id, author_id)
    WHERE deleted_at IS NULL;
CREATE INDEX idx_place_review_place_id ON public.place_review USING btree (place_id, id);
CREATE INDEX idx_place_review_author_id ON public.place_review USING btree (author_id);

CREATE TABLE public.place_review_report (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    review_id bigint NOT NULL,
    reporter_id bigint,
    reason character varying(20) NOT NULL,
    description character varying(200),
    status character varying(10) NOT NULL,
    processed_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT place_review_report_pkey PRIMARY KEY (id),
    CONSTRAINT place_review_report_review_id_fkey FOREIGN KEY (review_id)
        REFERENCES public.place_review (id) ON DELETE CASCADE,
    CONSTRAINT place_review_report_reason_check CHECK (
        reason IN ('ABUSE', 'SPAM', 'FALSE_INFO', 'PRIVACY', 'OTHER')),
    CONSTRAINT place_review_report_status_check CHECK (status IN ('PENDING', 'RESOLVED', 'REJECTED')),
    CONSTRAINT place_review_report_other_description_check CHECK (reason <> 'OTHER' OR description IS NOT NULL),
    CONSTRAINT place_review_report_processed_at_check CHECK ((status = 'PENDING') = (processed_at IS NULL))
);

-- 회원당 리뷰별 처리 대기 신고 1건.
CREATE UNIQUE INDEX uk_place_review_report_pending ON public.place_review_report USING btree (review_id, reporter_id)
    WHERE status = 'PENDING';
CREATE INDEX idx_place_review_report_review_id ON public.place_review_report USING btree (review_id, status);
CREATE INDEX idx_place_review_report_status ON public.place_review_report USING btree (status, created_at);
CREATE INDEX idx_place_review_report_reporter_id ON public.place_review_report USING btree (reporter_id);
