-- 동아리 쇼핑의 동아리·활동 분야·모집 건. 운영진·관련 링크는 조회 조건으로 쓰지 않는 짧은 목록이라 jsonb 배열로 둔다.
-- 기수제 동아리는 현재 기수와 활동 기간을 함께, 기수 없이 활동하는 동아리는 셋 다 비운다.
CREATE TABLE public.club (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name character varying(30) NOT NULL,
    affiliation character varying(20) NOT NULL,
    description character varying(1000) NOT NULL,
    generation integer,
    activity_start_date date,
    activity_end_date date,
    room_location character varying(50),
    generation_member_count integer,
    total_member_count integer,
    founded_date date,
    officers jsonb NOT NULL DEFAULT '[]'::jsonb,
    links jsonb NOT NULL DEFAULT '[]'::jsonb,
    registration character varying(15) NOT NULL,
    version bigint NOT NULL,
    info_updated_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT club_pkey PRIMARY KEY (id),
    CONSTRAINT club_affiliation_check CHECK (affiliation IN ('CENTRAL', 'DEPARTMENT', 'UNION', 'CAMPUS_ORG')),
    CONSTRAINT club_registration_check CHECK (registration IN ('PROVISIONAL', 'OFFICIAL')),
    CONSTRAINT club_generation_check CHECK (
        (generation IS NULL AND activity_start_date IS NULL AND activity_end_date IS NULL)
        OR (generation IS NOT NULL AND generation >= 1 AND activity_start_date IS NOT NULL AND activity_end_date IS NOT NULL
            AND activity_start_date <= activity_end_date)),
    CONSTRAINT club_member_count_check CHECK (
        (generation_member_count IS NULL OR generation_member_count >= 1)
        AND (total_member_count IS NULL OR total_member_count >= 1)),
    CONSTRAINT club_officers_check CHECK (jsonb_typeof(officers) = 'array' AND jsonb_array_length(officers) <= 5),
    CONSTRAINT club_links_check CHECK (jsonb_typeof(links) = 'array' AND jsonb_array_length(links) <= 3)
);

-- 활동 분야(동아리당 1~3개, 개수는 도메인이 검증).
CREATE TABLE public.club_field (
    club_id bigint NOT NULL,
    field character varying(30) NOT NULL,
    CONSTRAINT club_field_pkey PRIMARY KEY (club_id, field),
    CONSTRAINT club_field_club_id_fkey FOREIGN KEY (club_id) REFERENCES public.club (id) ON DELETE CASCADE,
    CONSTRAINT club_field_field_check CHECK (field IN (
        'PERFORMANCE', 'ACADEMIC', 'VOLUNTEER', 'SOCIAL_RELIGION', 'CULTURE_HOBBY', 'ART_CREATIVE',
        'SPORTS_LEISURE', 'STARTUP_GROWTH', 'SCIENCE_IT', 'BUSINESS_MARKETING', 'POLITICS_LAW',
        'MEDICAL_HEALTH', 'BEAUTY', 'COOKING_FOOD', 'ENVIRONMENT_ENERGY', 'CONTENT_MEDIA', 'EDUCATION',
        'STUDENT_COUNCIL'))
);

-- 기수별 모집 건. 기간 모집은 시작·마감 일시(한국 시간)를, 상시모집은 기간 없이 조기 마감만 쓴다.
-- 가장 최근 건이 현재 모집이고, 그 전 건들은 지난 모집으로 남긴다.
CREATE TABLE public.club_recruitment (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    club_id bigint NOT NULL,
    generation integer,
    always_open boolean NOT NULL,
    starts_at timestamp(6) without time zone,
    ends_at timestamp(6) without time zone,
    closed_early boolean NOT NULL,
    links jsonb NOT NULL DEFAULT '[]'::jsonb,
    notice character varying(1000),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT club_recruitment_pkey PRIMARY KEY (id),
    CONSTRAINT club_recruitment_club_id_fkey FOREIGN KEY (club_id) REFERENCES public.club (id) ON DELETE CASCADE,
    CONSTRAINT club_recruitment_generation_check CHECK (generation IS NULL OR generation >= 1),
    CONSTRAINT club_recruitment_period_check CHECK (
        (always_open AND starts_at IS NULL AND ends_at IS NULL)
        OR (NOT always_open AND starts_at IS NOT NULL AND ends_at IS NOT NULL AND starts_at < ends_at)),
    CONSTRAINT club_recruitment_links_check CHECK (jsonb_typeof(links) = 'array' AND jsonb_array_length(links) <= 3)
);

-- 동아리별 최근 모집 건 조회.
CREATE INDEX idx_club_recruitment_club_id ON public.club_recruitment USING btree (club_id, id);
